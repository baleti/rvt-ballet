"""viewer mesh vs Revit oracle over every file that has a gt_geom export (rosettas, scenes, corpus): convert (as rvt-view does) + compare_gt, one file at a time, resumable.
usage: tools/oracle_sweep.py run [stem ...]   -> ~/.cache/rvt-viewer/oracle_sweep.jsonl (one row per compared element: file, class, fidelity, iou, volume ratio, area ratio)
       tools/oracle_sweep.py table            -> docs/ORACLE-SWEEP.md (per class: n, fidelity buckets, median IoU, volume within 2 % / 10 %)   (run on host1 via h1run, ~1 s of CPU per small file, minutes for big)"""
import sys, os, json, glob, shutil, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ROOT); sys.path.insert(0, os.path.join(ROOT, 'tools'))
H = os.path.expanduser('~'); GT = H + '/rvt-research/gt_geom'; OUT = H + '/.cache/rvt-viewer/oracle_sweep.jsonl'; WORK = H + '/.cache/rvt-viewer/oracle-work'
MAXMB = float(os.environ.get('RVT_ORACLE_MAXMB', '60'))
def find(stem):
    base = stem[:-4] if stem.endswith('.tsv') else stem
    if base.endswith('.boxonly'): return None
    stems = [base] if os.path.splitext(base)[1] in ('.rvt', '.rte', '.rfa') else [base + e for e in ('.rte', '.rvt', '.rfa')]
    dirs = [H + '/rvt-research/rosetta/', H + '/rvt-research/write-lab/scenes/', H + '/rvt-research/write-lab/generated/']
    c = [d + x for d in dirs for x in stems]
    if base[:4].isdigit(): c += [g for x in stems for g in glob.glob(H + '/rvt-research/corpus/%s/%s' % (base[:4], x[5:]))]
    return next((x for x in c if os.path.exists(x)), None)
def run(stems):
    import subprocess
    done = set()
    if os.path.exists(OUT): done = {json.loads(l)['file'] for l in open(OUT)}
    for t in sorted(os.listdir(GT)) if not stems else stems:
        if not t.endswith('.tsv'): continue
        base = t[:-4]; src = find(t)
        if not src or base in done or os.path.getsize(src) > MAXMB * 1e6: continue
        p = subprocess.run([sys.executable, os.path.abspath(__file__), 'one', t], capture_output=True, text=True)      # one process per file: the reader's caches would add up to the memory cap
        if p.returncode != 0:
            with open(OUT, 'a') as f: f.write(json.dumps({'file': base, 'n': 0, 'error': 'exit %d %s' % (p.returncode, (p.stderr or '')[-150:]), 'rows': []}) + '\n')
            print(base, 'FAILED', p.returncode, flush=True)
        else: print(base, 'ok', flush=True)

def one(t):
    import compare_gt
    from rvtviewer import build
    base = t[:-4]; src = find(t); out = os.path.join(WORK, base); shutil.rmtree(out, ignore_errors=True); os.makedirs(WORK, exist_ok=True)
    if True:
        try:
            build.convert(src, out, log=lambda *a: None); compare_gt.main(out, GT)
            m = json.load(open(out + '/meta.json'))['elements']; c = json.load(open(out + '/compare.json'))['elements']
            rows = [{'file': base, 'cls': m[int(i)][1], 'fid': v.get('fid'), 'iou': v.get('iou'), 'vr': v.get('vratio'), 'ar': v.get('aratio')} for i, v in c.items()]
            err = None
        except BaseException as ex: rows = []; err = repr(ex)[:200]
        with open(OUT, 'a') as f:
            f.write(json.dumps({'file': base, 'n': len(rows), 'error': err, 'rows': rows}) + '\n')
        shutil.rmtree(out, ignore_errors=True)
def table():
    import statistics as S
    R = collections.defaultdict(list); files = 0; errs = []
    for l in open(OUT):
        r = json.loads(l); files += 1
        if r['error']: errs.append((r['file'], r['error']))
        for x in r['rows']: R[x['cls']].append(x)
    L = ['# Viewer mesh vs Revit oracle (gt_geom) per class', '', 'Generated by tools/oracle_sweep.py: %d files with a Revit export, every compared element (bbox IoU, volume ratio of the converted mesh to Revit\'s solid at Fine detail). Fidelity = what the viewer drew (exact/true geometry, matched, approx, box).' % files, '',
         '| class | n | fidelity (true / approx / box) | median IoU | IoU >= 0.95 | volume within 2 % | within 10 % (n measured) |', '|---|---|---|---|---|---|---|']
    for c, xs in sorted(R.items(), key=lambda kv: -len(kv[1])):
        fid = collections.Counter(x['fid'] for x in xs); box = fid.get('bbox', 0) + fid.get('box', 0); ap = fid.get('approx', 0); tr = len(xs) - box - ap
        ious = [x['iou'] for x in xs if x['iou'] is not None]; vr = [x['vr'] for x in xs if x['vr']]
        L.append('| %s | %d | %d / %d / %d | %.3f | %s | %s | %s |' % (c, len(xs), tr, ap, box, S.median(ious) if ious else float('nan'), '%d%%' % (100 * sum(i >= .95 for i in ious) / len(ious)) if ious else '', '%d%%' % (100 * sum(abs(v - 1) <= .02 for v in vr) / len(vr)) if vr else '', '%d%% (%d)' % (100 * sum(abs(v - 1) <= .10 for v in vr) / len(vr), len(vr)) if vr else ''))
    if errs: L += ['', '## Files that failed', ''] + ['* %s: %s' % e for e in errs]
    open(os.path.join(ROOT, 'docs', 'ORACLE-SWEEP.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L[:12]))
if __name__ == '__main__':
    if sys.argv[1] == 'run': run(sys.argv[2:])
    elif sys.argv[1] == 'one': one(sys.argv[2])
    else: table()
