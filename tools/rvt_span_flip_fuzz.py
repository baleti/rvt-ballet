#!/usr/bin/env python3
"""rvt_span_flip_fuzz.py SRC.rvt GOOD.rvt MANIFEST_ELID N : single-bit flips inside the byte range where GOOD differs from SRC (the edited, re-cut member),
fed to save_as with the real manifest of a Comments edit. ESCAPE = accepted although the output differs from GOOD. Local files only; prints aggregate numbers."""
import os, sys, random, shutil, tempfile
T = tempfile.mkdtemp(); sys.path[:0] = [os.path.expanduser('~/src/rvt-viewer'), os.path.expanduser('~/src/savegate'), os.path.expanduser('~/src/rvt-ballet')]
open(T+'/c.json','w').write('{"allow_overwrite": true}'); open(T+'/g.json','w').write('{"rvt": {"*": "open"}}')
os.environ.update(SAVEGATE_JOURNAL=T+'/j', SAVEGATE_CACHE=T+'/c', DWG_BALLET_CONFIG=T+'/c.json', SAVEGATE_GATE=T+'/g.json', RVTBALLET_EDIT_BACKEND='rvtedit')
from rvtballet import save
src, good, elid, n = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
S = open(src,'rb').read(); G = open(good,'rb').read()
p = T+'/m.rvt'; shutil.copy(src, p); ss = save.SaveSessions(); d = ss.doc('m', p)
save.add_edit(ss, 'm', p, {"op":"set_string","eid":elid,"param":"Comments","value":os.environ["VAL"]})
nb, man = save._pending(ss, 'm', d, None, None)
if nb != G: print('note: regenerated output differs from GOOD; fuzzing the regenerated bytes'); G = nb
diff = [i for i in range(min(len(S), len(G))) if S[i] != G[i]]
lo, hi = diff[0], diff[-1]; print('diff window', hi - lo + 1, 'bytes of', len(G), flush=True)
rng = random.Random(219); C = {}; esc = []
for t in range(n):
    pos = rng.randint(lo, hi); b = bytearray(G); b[pos] ^= 1 << rng.randrange(8)
    dest = '%s/o%d.rvt' % (T, t)
    try: save.save_as(ss, 'm', p, dest, new_bytes=bytes(b), manifest=man); r = 'accepted'
    except Exception as e: r = type(e).__name__ + ':' + str(e)[:40].split(':')[0]
    if r == 'accepted':
        esc.append(pos); r = 'ACCEPTED'
    C[r] = C.get(r, 0) + 1
    if os.path.exists(dest): os.remove(dest)
print(C); print('accepted-flip offsets (inspect for equivalence):', esc)
shutil.rmtree(T, ignore_errors=True)
